const assert = require("assert");
const { InMemoryAuthority, InMemoryDualTrade, validateIntent } = require("../dist/authority");
const { sharedCatalogDocument, validateSharedCatalog } = require("../dist/catalog_contract");
const catalog = sharedCatalogDocument();
assert.deepEqual(validateSharedCatalog(catalog), []);
assert.equal(catalog.schema, "printforge.v3.catalog");
assert.equal(catalog.cards.length, 57);
assert.equal(catalog.cards.filter((card) => card.type === "creature").length, 24);
const cinderpaw = catalog.cards.find((card) => card.id === "cinderpaw");
assert.deepEqual({ bend:cinderpaw.bend_score, hp:cinderpaw.hp, element:cinderpaw.element, cost:cinderpaw.filament_cost, turns:cinderpaw.print_turns }, { bend:18, hp:34, element:"Fire", cost:70, turns:1 });
const ring = catalog.cards.find((card) => card.id === "filament_ring");
assert.deepEqual({ type:ring.type, slot:ring.equipment_slot, cost:ring.filament_cost, turns:ring.print_turns }, { type:"equipment", slot:"battle_effect", cost:75, turns:0 });
const nonCreatures = catalog.cards.filter((card) => card.type !== "creature");
assert.equal(nonCreatures.length, 33);
const visibleArt = nonCreatures.map((card) => card.art.path ? `path:${card.art.path}` : `atlas:${card.art.atlas}:${card.art.cell}`);
assert.equal(new Set(visibleArt).size, 33);
assert.deepEqual(ring.art, { path:"res://assets/cards/v3/filament_ring_art_v1.png" });
const arcaneSuit = catalog.cards.find((card) => card.id === "arcane_full_suit");
assert.deepEqual({ slot:arcaneSuit.equipment_slot, cost:arcaneSuit.filament_cost, turns:arcaneSuit.print_turns }, { slot:"armor", cost:120, turns:3 });
assert.equal(validateIntent(null), false);
assert.equal(validateIntent({ type:"play_card" }), false);
assert.equal(validateIntent({ type:"play_card", cardId:42 }), false);
assert.equal(validateIntent({ type:"attack", slot:0 }), false);
assert.equal(validateIntent({ type:"attack", slot:0, target:1 }), true);
assert.equal(validateIntent({ type:"upgrade_reprint", graveyardIndex:0 }), true);
assert.equal(validateIntent({ type:"upgrade_reprint", graveyardIndex:-1 }), false);
const authority = new InMemoryAuthority();
assert.equal(authority.submit({ seat:1, expectedRevision:0, intent:{type:"advance_phase"} }).reason, "wrong_seat");
assert.equal(authority.submit({ seat:0, expectedRevision:2, intent:{type:"advance_phase"} }).reason, "stale_revision");
assert.equal(authority.submit({ seat:0, expectedRevision:0, intent:{type:"bad"} }).reason, "illegal_intent");
assert.equal(authority.submit({ seat:0, expectedRevision:0, intent:{type:"advance_phase"} }).revision, 1);
const response = authority.submit({ seat:1, expectedRevision:1, intent:{type:"advance_phase"} }); response.snapshot.turn = 999; assert.notEqual(authority.snapshot.turn, 999);
const trade = new InMemoryDualTrade(["a"], ["b"], 4, 7);
assert.equal(trade.confirm(0, 4, 7, "a", "b").settled, false);
assert.equal(trade.confirm(1, 3, 7, "a", "b").reason, "stale");
assert.equal(trade.confirm(1, 4, 7, "a", "b").settled, true);
assert.deepEqual(trade.creator, ["b"]); assert.equal(trade.audit.length, 1); assert.equal(trade.confirm(0, 5, 8, "a", "b").reason, "settled");
console.log("PASS: v3 shared catalog parity, in-memory authority and dual-confirm local trade");
