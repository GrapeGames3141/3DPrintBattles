#!/usr/bin/env python3
"""Writes the generated catalog files in scripts/core/catalog/ from the tables
in this package. Run from the repository root:

    python3 tools/catalog/build.py

Art is made separately (tools/make_creatures.py and the Godot render scripts).
"""
import json
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
from catalog.cards import TOOLS, UPGRADES  # noqa: E402
from catalog.creatures import CREATURES  # noqa: E402
from catalog.mods import CARD_MODS, PRINTER_MODS  # noqa: E402
import catalog.wave6  # noqa: E402,F401  (adds its cards to the lists above)

OUT = os.path.join(os.path.dirname(__file__), "..", "..", "scripts", "core", "catalog")


def gd(v, depth=0):
    """A Python value as a GDScript literal."""
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return json.dumps(v)
    if isinstance(v, list):
        return "[" + ", ".join(gd(x, depth + 1) for x in v) + "]"
    if isinstance(v, dict):
        return "{" + ", ".join("%s: %s" % (json.dumps(k), gd(x, depth + 1)) for k, x in v.items()) + "}"
    raise TypeError(type(v))


def write(name, doc, rows, strip=()):
    lines = ["extends RefCounted", "## " + doc, "## Generated by tools/catalog/build.py. Edit the tables there, not this file.", "", "const LIST := ["]
    for r in rows:
        row = {k: v for k, v in r.items() if k not in strip}
        # keep rows tidy: drop empty optional fields
        row = {k: v for k, v in row.items() if not (v in ("", [], 0) and k in ("target", "on_print", "shatter", "special", "atk", "hp", "dcost", "kw", "fx_on", "fx_sh", "line_on", "line_sh") and r.get("type") != "creature")}
        lines.append("\t" + gd(row) + ",")
    lines.append("]")
    path = os.path.join(OUT, name)
    os.makedirs(OUT, exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", path, len(rows))


def main():
    for c in CREATURES:
        if not c["on_print"]:
            c.pop("on_print")
        if not c["shatter"]:
            c.pop("shatter")
        if not c["target"]:
            c.pop("target")
    looks = {c["id"]: c["look"] for c in CREATURES if "look" in c}
    with open(os.path.join(os.path.dirname(__file__), "looks.json"), "w") as f:
        json.dump(looks, f, indent=1, sort_keys=True)
    print("wrote looks.json", len(looks))
    write("catalog_creatures.gd", "Creature cards.", CREATURES, strip=("art", "look"))
    write("catalog_tools.gd", "Tool cards.", TOOLS)
    with open(os.path.join(OUT, "catalog_retired.gd"), "w") as f:
        f.write("extends RefCounted\n## Cards taken out of the game, with their rarity, so owners can be paid for them.\n"
                "## Generated by tools/catalog/build.py.\n\nconst LIST := " + gd(dict(sorted(catalog.wave6.RETIRED.items()))) + "\n")
    print("wrote catalog_retired.gd", len(catalog.wave6.RETIRED))
    write("catalog_upgrades.gd", "Equipment cards.", UPGRADES)
    write("catalog_card_mods.gd", "Card mods.", CARD_MODS)
    write("catalog_printer_mods.gd", "Printer mods.", PRINTER_MODS)


if __name__ == "__main__":
    main()
